    <h1 class="post-title">They should be learning instead of watching</h1>
    <time class="post-date">August 6, 2026</time>

    <p>Everyone has the potential to lead. I believe that plainly, not as a nice thing to say. The capacity is ordinary and it's sitting in almost everybody, unspent.</p>

    <p>What is not ordinary is spending it.</p>

    <p>There is a line in Ratatouille that gets quoted constantly and usually gets quoted wrong. Anyone can cook. People hear that as a promise, as though effort converts into greatness if you put enough in. The version that holds up comes later, from the critic:</p>

    <blockquote class="ink-quote">
      <p>Not everyone can become a great artist, but a great artist can come from anywhere.</p>
    </blockquote>

    <p>That's colder and more useful. It refuses to promise you the outcome, and it also refuses to let you rule yourself out, because the thing you'd use to disqualify yourself, where you came from, isn't predictive. Leadership works the same way. Not everyone becomes good at it, and anyone might.</p>

    <p>So what converts the potential into the thing?</p>

    <p>The willingness to take the first step when nobody around you is sure.</p>

    <p>I want to be precise about what that costs, because this is where most writing about leadership goes soft. You're not weighing a good option against a bad one. You're looking at A and B without knowing what either of them does. You might be wrong, and you might be publicly wrong. There's embarrassment in it, sometimes real pain, and sometimes you carry the consequence for years. The person who steps knows all of that and steps anyway.</p>

    <p>Courage on its own isn't enough, though, and I'd rather say that early than let this become an essay about being brave. There are people who act decisively toward nothing in particular, and following them is how you end up somewhere nobody wanted to go. A leader is executory. They build, and I mean that in the sense of construction rather than trade: builders of ideas, builders of plans, and then builders of the reality those plans describe. The step is the first move in executing something that already exists in their head.</p>

    <p>This explains something people say about leaders without ever explaining it. A leader creates certainty when everything is uncertain. That sounded like magic to me until I worked out the mechanism, and the mechanism is boring. The leader is not certain they are right. They have built a picture of the far side and committed to walking toward it, while everyone else is uncertain because they have not built anything to be certain about.</p>

    <p>None of this requires a team. That's the organizational version of leadership and it gets mistaken for the whole thing. You don't need anyone assigned to you, you need to move, and you need someone to see you do it. The seeing is what turns a decision into leadership rather than just a decision.</p>

    <h2>Why anyone follows you</h2>

    <p>Here is the obvious objection. What about a military officer? They give an order, the order gets followed, and nobody consulted anyone about inspiration. Authority does the work.</p>

    <p>Except it doesn't do the work people think it does. Rank buys compliance and cannot buy belief.</p>

    <p>Why would I follow orders if I don't trust you? I might obey them, which is a different thing, and the difference shows up the moment the authority is gone. Compliance ends when the person with the rank leaves the room, and trust is what converts obedience into something that survives that. No title grants it, which is why plenty of people hold positions of authority and lead nobody at all.</p>

    <p>That matters for everything below, because nobody learns from a person they don't trust. They do what they're told and wait for it to be over.</p>

    <h2>A leader is a teacher</h2>

    <p>Every leader expires. Not dramatically. You run out of time, or the role changes, or your attention goes elsewhere, or your health does. If the people around you can only wait for direction, then the moment you're gone you've left nothing behind that works.</p>

    <p>So I think a leader is a teacher, and I mean something narrow by that. Teaching here is demonstration rather than curriculum. You act, people watch, and something transfers. They should be learning instead of watching.</p>

    <p>What transfers is the method, which is where the builder idea pays off. If all anyone learns from you is that you were brave, they've learned nothing usable, because courage is not a technique. What they can learn from watching a builder is how a person gets from nothing to a plan, and from a plan to a thing that exists. That's portable, and it's the reason good successors aren't limited to finishing your work. They didn't inherit your plan. They watched somebody build one, so they can go build their own, and it might have nothing to do with what you were doing.</p>

    <p>Growth is the output. Teaching is the mechanism that produces it. Worth keeping those apart, because plenty of leaders talk about developing people while doing nothing anyone could learn from.</p>

    <h2>The building on fire</h2>

    <p>Someone in a burning building is not developing anyone. There's no growth happening in a stairwell. They're getting people to the exits, counting heads, and making calls in seconds that they will second-guess for years afterward. They are also leading, more clearly than most people who hold the title.</p>

    <p>I used to think this broke the frame. It doesn't, once you stop confusing teaching with instruction. What that person demonstrates, under conditions where it isn't the default, is that calm was available, that it was possible to think while everything was on fire. Nobody in that stairwell turns into a copy of them and nobody needs to. They saw a person do something they didn't know a person could do, and they will carry it, and some of them will find it in themselves later in a room that isn't on fire at all.</p>

    <p>That's teaching with everything stripped out except demonstration, and it still works, which tells you demonstration was the load-bearing part the whole time.</p>

    <h2>The one who wins</h2>

    <p>Picture a leader who meant well and delivered. The objective was real, the objective was reached, and they got there by rolling over their own people. Not enemies, their own, the ones who followed them. Judged on outcome, this person passes, and that's what makes them hard.</p>

    <p>Notice that they teach, by the definition I've been using. They demonstrate, people watch, something transfers, and what transfers is that this is what winning requires. That lesson is portable too. It propagates through the next generation of people who learned leadership by watching them, and the damage keeps compounding long after everyone has forgotten where it came from.</p>

    <p>So demonstration cannot be the whole test, because it passes people it should not. The direction has to be attached to it.</p>

    <p>The sharpest way I can put the difference is that this leader builds effectively. That's the whole difficulty, they're genuinely good at it. But they build with people rather than building people, and both are supposed to happen at once. The plan gets built and so do the people executing it. Someone who achieves the first by spending the second has done half the job and charged the rest to somebody else.</p>

    <p>Which gives one test that works whether you succeeded or failed. Did the people around you leave more capable than they arrived, or more damaged?</p>

    <p>I do not accept the end justifying the means. It's cruel, and I think people reach for it mostly when they've already decided what they want to do. But I'd rather make the argument than just recoil from it, so: the person who wins this way has not maximized anything. They ran a small ledger. They booked the objective and expensed the people, and the capability that never got built doesn't appear anywhere in their accounting because it never existed to be counted. Widen the ledger and the sum goes negative. They didn't win, they moved the loss to someone else's scorecard.</p>

    <h2>What it costs, and what it costs too much</h2>

    <p>There is a character in Andor, Luthen, a spymaster, who is the clearest version of this I've seen put on screen. He isn't what you picture when you picture a leader. No army, no title, no speeches to crowds. He recruits people, dispatches them, and directs a plan that almost nobody he commands can see the shape of. He is also the most honest anyone has been about the price, and he says it himself:</p>

    <blockquote class="ink-quote">
      <p>I burn my life to make a sunrise that I know I'll never see.</p>
    </blockquote>

    <p>No ease, no peace, no love, no sleep, and no mirror he can look into. He burns his decency for someone else's future.</p>

    <p>I'm not going to rescue him. He fails the test I just described. He spends people, including the ones who trusted him most, and he knows he's doing it. Morally he is atrocious, and he is unmistakably leading, which is inconvenient for anyone who wants leadership and virtue to be the same word. But look at where he ends up. Everyone left. The one person who stayed was raised into the work from childhood and carries the same emptiness he does, because that's what he built into her. She isn't the proof that somebody loved him, she's the evidence of what proximity to him did to a person. He built an apprentice and the building is what damaged her. What he transmitted was the wound, it propagated exactly as designed, and it disqualifies him under his own results.</p>

    <p>Compare Cassian, who he recruited, and whose story ends in a sacrifice as final as anything the spymaster paid. Same currency, completely different accounting. Luthen paid continuously, for decades, until there was nothing left in him to spend. Cassian paid once, at the end, on purpose, for people he actually knew and could name. He was a good soldier and a good man. I wouldn't call him a good leader and I don't think the story asks me to. He's proof that you can pay the price without the price eating you first.</p>

    <h2>Meaning well</h2>

    <p>Here is the part I have never fully worked out, and I'd rather show you the shape of the problem than pretend I've solved it.</p>

    <p>My standing position is that a man should be judged by his actions, not his intentions. I've believed that a long time and I still do. The trouble is that everything above asks people to act under uncertainty, which guarantees some of them will fail while meaning well. So either my leadership frame is wrong or my position on intentions is, and for a while I couldn't tell which.</p>

    <p>Part of it does resolve. Intentions are the permission, not the verdict. Meaning well is what entitles you to act on somebody else's behalf in the first place, and without it you're not a failed leader, you're someone who used people. Once the damage is done, though, meaning well stops being a defense and becomes biography. It explains the trajectory without reducing the wreckage. Good intentions buy the standing to try and never buy a discount on the judgment.</p>

    <p>That's clean, and I don't believe it's enough.</p>

    <p>Look at where the worst things actually come from. Children who resent their parents. Parents who resent their children. Families that come apart. Relationships that fail slowly and then all at once. Go back through any of them and you find people who meant well. Nobody set out to do the damage, the good intentions were real, and they were exactly what drove the actions that did it.</p>

    <p>So the good-intentions defense turns out to be two things at once. It's the most human thing a person can offer, and it's the most common cover story for harm anybody has ever used, and you cannot tell which one you're looking at from the inside. That includes when it's you.</p>

    <h2>Asking yourself what the hell you are doing</h2>

    <p>That limit is real and it doesn't get you out of anything.</p>

    <p>You cannot audit your own motives perfectly. Nobody can. What follows is not permission to skip the attempt, and skipping it is where most of the damage in the world comes from. Not evil, almost never evil. People move without ever stopping to ask what they're doing, or why, or who told them it was a good idea. They just do.</p>

    <p>So introspection is unreliable and mandatory at the same time. You won't get a clean answer, and you ask anyway. When the answer comes back badly, when you catch yourself and the honest reading is that you were protecting yourself or proving something or afraid, you take it and you change something.</p>

    <p>Which brings me to what a leader who failed still owes. They owe the people who followed them, and not in a vague way. Those people were exposed by a decision that wasn't theirs, the exposure was your doing, and failing doesn't dissolve it. The obligation survives the outcome, and it might be the only thing that does.</p>

    <p>Concretely: you stay. Leaving is easier and usually available and you don't take it. You tell them plainly what went wrong, which means giving up control of the story, because managing the narrative is protecting yourself with extra steps. And you don't let them carry blame that belongs to you, even when they're willing to, even when it would be convenient, especially then.</p>

    <p>I used to call this accepting the consequences. That isn't right. Consequences are things that happen to you, and this is active. You turn around and face the people who moved because you moved, and you do the work of making the failure into something they can use. Anyone can demonstrate well when it's working. The obligation is to keep demonstrating when it isn't, and what you're demonstrating at that point is how to lose without lying about it.</p>

    <p>This is what I mean by a growth mindset, and I want to be exact because the phrase has been worn smooth. I don't mean resilience or bouncing back. I mean being willing to find out you were wrong about yourself, which is harder than being wrong about a decision, and which is why most people arrange their lives so it never comes up.</p>

    <h2>Four brakes and one accelerator</h2>

    <p>I should say where this came from, because it didn't come from a framework. I took CliftonStrengths a few years ago through a leadership training, and I already thought most of what is written above before I sat down for it. What the assessment did was explain the mechanism underneath, which is a smaller job than people usually give these things credit for.</p>

    <p>My top five, in order: Deliberative, Responsibility, Activator, Analytical, Context. Four of those are brakes.</p>

