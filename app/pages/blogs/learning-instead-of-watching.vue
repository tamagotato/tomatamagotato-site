    <p>Both of those cannot be describing the same person.</p>

    <p>There are gentle explanations available. Two years is enough time to change. The two instruments might be measuring different layers, one asking how you come across and the other where your instincts run, in which case people could genuinely see a Driver because my deliberation is fast and happens where nobody can watch it.</p>

    <p>I don't think that's what happened. CliftonStrengths is closer to how I actually operate, so the Driver result is the one to be suspicious of, and the simplest explanation is that I answered as the person I wanted to be. Fast to decide. Takes risks. Carefree. Those are aspirational for someone whose first instinct is to look for what could go wrong.</p>

    <p>Nobody sits down planning to inflate a self-assessment. It happens because answering honestly requires already knowing yourself in exactly the way the questionnaire claims it is about to tell you, and if you had that, you wouldn't need the questionnaire.</p>

    <p>Which is the whole argument arriving at my expense. I've been saying that people don't have an easy time understanding what they're doing, that they just do, and that you have to ask anyway even though the asking is unreliable. Here is me, in a room built for self-knowledge, handed an instrument designed to give it to me, getting myself wrong.</p>

    <h2>The step</h2>

    <p>Everyone has the potential and almost nobody spends it. The step costs something real. It's a step toward something you built, which is where the certainty comes from, and it's watched, and the watching is what teaches, and what gets taught is the method rather than the nerve. It might fail. If it does, the people who moved because you moved are still there, and you still owe them, and the failing doesn't release you from that.</p>

    <p>That is the whole thing. It isn't complicated, it's expensive, and the expense is why so few people take the step and why it means something when they do.</p>

    <p>These are my thoughts, and I don't expect anyone to agree with all of them. Some of this is worked out and some of it clearly isn't, and I've tried to be honest about which is which rather than smoothing the whole thing into something tidier.</p>

    <p>And I'd guess that two or three years from now I'll sit down for another one of these and find myself arguing with things I've written here. That would be the point. An essay that told you to be willing to find out you were wrong about yourself, and then held its positions forever, wouldn't have meant any of it.</p>
